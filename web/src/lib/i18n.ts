export type Copy = (typeof UI)[Lang];

export function formatNumber(value: number, lang: Lang, digits = 0) {
  return new Intl.NumberFormat(lang === "de" ? "de-DE" : "en-GB", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(value);
}

export function formatPercent(share: number, lang: Lang) {
  return lang === "de" ? `${formatNumber(share * 100, lang)} %` : `${formatNumber(share * 100, lang)}%`;
}

export function formatSeconds(seconds: number, lang: Lang) {
  return `${formatNumber(seconds, lang, seconds < 0.1 ? 3 : 2)} s`;
}
